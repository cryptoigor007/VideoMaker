# слова, которые НЕ красим в одиночку (только в составе идиомы)
SINGLE_BLOCKLIST: set[str] = {
    "для", "друг",  # «друг» только в идиоме или если Gemini явно + сосед
    "раза", "раз", "дело", "деле", "все", "всё", "это", "того", "этом",
    "самом", "самый", "самая", "самое",
}

def _norm(s: str) -> str:
    import re
    t = (s or "").strip().lower().replace("ё", "е")
    t = re.sub(r"^[\s\.,!?;:«»\"\'()\[\]…—–\-]+", "", t)
    t = re.sub(r"[\s\.,!?;:«»\"\'()\[\]…—–\-]+$", "", t)
    return t


def lexicon_level(word: str) -> str:
    """Уровень одиночного слова или ''."""
    k = _norm(word)
    if not k or len(k) < 2 or k in SINGLE_BLOCKLIST:
        return ""
    if k in LEX_L4:
        return "L4"
    if k in LEX_L3:
        return "L3"
    if k in LEX_L2:
        return "L2"
    return ""


def find_idioms_in_words(word_texts: list[str]) -> list[tuple[int, int, str]]:
    """Найти идиомы в последовательности слов.

    Returns list of (start_idx, end_idx_exclusive, level).
    Жадный longest-match слева направо.
    """
    norms = [_norm(w) for w in word_texts]
    n = len(norms)
    # sorted idioms by length desc
    idioms = sorted(IDIOM_PHRASES.items(), key=lambda x: -len(x[0].split()))
    used = [False] * n
    found: list[tuple[int, int, str]] = []
    i = 0
    while i < n:
        if used[i]:
            i += 1
            continue
        matched = False
        for phrase, level in idioms:
            parts = phrase.split()
            L = len(parts)
            if i + L > n:
                continue
            if norms[i : i + L] == parts and not any(used[i : i + L]):
                for j in range(i, i + L):
                    used[j] = True
                found.append((i, i + L, level))
                i += L
                matched = True
                break
        if not matched:
            i += 1
    return found


def build_lexicon_strong_map(word_texts: list[str]) -> dict[str, str]:
    """Карта norm_word → level только из лексикона + идиом (без Gemini)."""
    m: dict[str, str] = {}
    rank = {"L1": 1, "L2": 2, "L3": 3, "L4": 4}
    # идиомы целиком
    for a, b, level in find_idioms_in_words(word_texts):
        for j in range(a, b):
            k = _norm(word_texts[j])
            if not k:
                continue
            prev = m.get(k)
            if prev is None or rank.get(level, 0) >= rank.get(prev, 0):
                m[k] = level
    # одиночные
    for w in word_texts:
        k = _norm(w)
        if not k or k in m:
            continue
        if k in SINGLE_BLOCKLIST:
            continue
        lv = lexicon_level(w)
        if lv:
            m[k] = lv
    return m
